test('Phase 4 / Jornal: observer animates ONLY original archive images and restores without touching old stories',()=>{
 const w=new JSDOM(decorateJournal(journalMarkup),{runScripts:'outside-only',url:'https://www.francoromeufr.com.br/projetos/'}).window,d=w.document;
 w.matchMedia=()=>({matches:false});
 let observeTargets=[],callback;
 w.IntersectionObserver=class{constructor(cb){callback=cb;}observe(el){observeTargets.push(el)}unobserve(){}disconnect(){}};
 w.eval(read('assets/js/fr-journal-phase4.js'));
 d.dispatchEvent(new w.Event('DOMContentLoaded'));
 assert.equal(w.FRJornalMotion4.getState().mounted,true);
 assert.equal(w.FRJornalMotion4.getState().total,2);
 assert.equal(observeTargets.length,2);
 assert.equal(d.querySelectorAll('#frap-journal [data-frj4-visible]').length,0);
 callback([{target:observeTargets[0],isIntersecting:true}]);
 assert.equal(w.FRJornalMotion4.getState().revealed,1);
 w.FRJornalMotion4.destroy();
 assert.equal(d.body.classList.contains('frj4-motion-ready'),false);
 assert.equal(d.querySelectorAll('#arquivo .frj-index-card').length,2);
 assert.equal(d.getElementById('frap-journal').isConnected,true);
 w.close();
});
